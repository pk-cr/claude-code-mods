# Writes the studio crew's sprite grids as a TypeScript data module (the mod's hooks/crew.ts).
# Run: python -I export_crew.py [out.ts]   (default: ../agent-radar/hooks/crew.ts; chibi.py imports Pillow, so use a Python that has it.)
import os, sys, json
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import chibi_studio as cs
import arena_export
from chibi import W, H

ROLES = {
    'lead': 'director Kaito', 'explore': 'location scout Pip', 'scout': 'sound engineer Rachael', 'plan': 'storyboard artist Mira',
    'architect': 'producer Vance', 'reviewer': 'QC editor Ren', 'builder': 'animator Bolt', 'researcher': 'archivist Sora',
    'general': 'assistant', 'other': 'intern',
}
MOODS = ['normal', 'work', 'wow', 'sleepy', 'happy', 'stuck']
POSES = ['stand', 'step-a', 'step-b']

def rows(g, a, b):
    return [''.join(c if c else '.' for c in g[y]) for y in range(a, b)]

out = []
out.append('// GENERATED by agent-radar-art/export_crew.py: the animation-studio crew as 20 by 28 grids. Do not edit by hand.')
out.append('// One character per palette key (see peopleColors in office.ts); `.` is empty. Heads (rows 0-17) change with the')
out.append('// mood, bodies (rows 18-23) with the standing/seated view, legs (rows 24-27) with the walking pose.')
out.append('')
out.append("export type Mood = 'normal' | 'work' | 'wow' | 'sleepy' | 'happy' | 'stuck'")
out.append("export type Pose = 'stand' | 'step-a' | 'step-b'")
out.append("export type CrewRole = " + ' | '.join("'%s'" % r for r in ROLES))
out.append('export type CrewSprite = {')
out.append('  /** Rows 0-17 by mood. */')
out.append('  head: Readonly<Record<Mood, readonly string[]>>')
out.append('  /** Rows 18-19: what shows above a desk. */')
out.append('  seatBody: readonly string[]')
out.append('  /** Rows 18-23 with the held item, for a standing or walking person. */')
out.append('  body: readonly string[]')
out.append('  /** Rows 24-27 by pose. */')
out.append('  legs: Readonly<Record<Pose, readonly string[]>>')
out.append('}')
out.append('export type CrewLook = { hair: string; eyes: string; skin: string; outfit: string; accent: string; kit: string; pants: string }')
out.append('')
looks = {}
sprites = {}
for role, name in ROLES.items():
    look = cs.CREW[name]
    nohold = dict(look, held=None, quirks=[q for q in look.get('quirks', []) if q != 'tail'])
    head = {m: rows(cs.build(nohold, m, 'stand'), 0, 18) for m in MOODS}
    # standing heads carry quirks that live in the head rows only, so the same heads serve both views
    seat = rows(cs.build(nohold, 'normal', 'stand'), 18, 20)
    body = rows(cs.build(look, 'normal', 'stand'), 18, 24)
    legs = {p: rows(cs.build(look, 'normal', p), 24, 28) for p in POSES}
    sprites[role] = dict(head=head, seatBody=seat, body=body, legs=legs)
    looks[role] = dict(hair=look['hair'], eyes=look['eye'], skin=look['skin'], outfit=look['outfit'], accent=look['accent'], kit=look['kit'], pants=look['pants'])
    for r in head['normal'] + seat + body:
        assert len(r) == W, (role, r)

def ts(v, ind=2):
    return json.dumps(v, indent=ind).replace('"', "'")

out.append('export const CREW_LOOKS: Readonly<Record<CrewRole, CrewLook>> = ' + ts(looks) + '')
out.append('')
out.append('export const CREW: Readonly<Record<CrewRole, CrewSprite>> = ' + ts(sprites) + '')
out.append('')
arena_sprites, arena_looks, arena_names = arena_export.arena()
out.append("/** The gauntlet's cast: eight gladiators (one per competitor letter A to H) and eight judges, drawn only while a gauntlet runs. */")
out.append("export type ArenaRole = 'gladiator' | 'judge'")
out.append('export const ARENA: Readonly<Record<ArenaRole, readonly CrewSprite[]>> = ' + ts(arena_sprites) + '')
out.append('')
out.append('export const ARENA_LOOKS: Readonly<Record<ArenaRole, readonly CrewLook[]>> = ' + ts(arena_looks) + '')
out.append('')
out.append('export const ARENA_NAMES: Readonly<Record<ArenaRole, readonly string[]>> = ' + ts(arena_names) + '')
out.append('')
emperor_sprite, emperor_look = arena_export.emperor()
out.append("/** The Lead while the colosseum is on: the same director Kaito, in a laurel wreath, gold armor and a cape. */")
out.append('export const EMPEROR: CrewSprite = ' + ts(emperor_sprite) + '')
out.append('')
out.append('export const EMPEROR_LOOK: CrewLook = ' + ts(emperor_look) + '')
out.append('')
target = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'agent-radar', 'hooks', 'crew.ts')
open(target, 'w').write('\n'.join(out))
print('wrote', target, sum(len(x) for x in out), 'chars')
